import { test, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";

test("coordenador cria grupo com foto, corrige imagem inválida e atualiza a capa", async ({ page, context }, testInfo) => {
  const viewport = testInfo.project.name;
  const name = `A Grupo ${viewport}`;
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await context.route("**/*", (route) => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort());
  await page.goto("/painel/grupos/novo");
  await expect(page).toHaveURL(/login.html$/);
  await page.getByLabel("E-mail", { exact: true }).fill(`${viewport}.group-coordinator@example.invalid`);
  await page.getByLabel("Senha", { exact: true }).fill("GroupBrowserTest!81-Pass");
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await expect(page).toHaveURL(/painel\/grupos\/novo$/);
  await page.goto("/grupos.html");
  await page.getByRole("link", { name: "Criar novo grupo" }).click();
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("Criar novo grupo");
  await expect(page.getByRole("heading", { name: "Enviar imagem do grupo", exact: true })).toBeVisible();
  await expect(page.getByRole("radio")).toHaveCount(0);
  await page.getByRole("textbox", { name: "Nome do grupo", exact: true }).fill(name);
  await page.getByRole("textbox", { name: "Apresentação", exact: true }).fill("Um novo grupo de oração e formação.");
  await expect(page.getByText(/Recomendado: 1600 × 900 px/)).toBeVisible();
  await expect(page.getByRole("checkbox", { name: "Grupo ativo no site" })).toHaveCount(0);
  await page.getByLabel("Escolher foto do grupo").setInputFiles(process.env.CUC_GROUP_SMALL_PHOTO);
  await page.getByRole("textbox", { name: "Descrição da foto" }).fill("Foto de teste do novo grupo");
  await page.getByRole("button", { name: "Criar grupo", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "no mínimo 800" })).toBeVisible();
  await expect(page.getByRole("textbox", { name: "Nome do grupo", exact: true })).toHaveValue(name);
  await page.getByLabel("Escolher foto do grupo").setInputFiles(process.env.CUC_GROUP_PHOTO);
  await expect(page.locator(".management-group-preview img")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await mkdir("../.local/groups-live/screenshots", { recursive: true });
  await page.screenshot({ path: `../.local/groups-live/screenshots/${viewport}-criar-grupo.png`, fullPage: true });
  await page.getByRole("button", { name: "Criar grupo", exact: true }).click();
  await expect(page).toHaveURL(/painel\/grupos$/);
  await expect(page.getByRole("status").filter({ hasText: `Grupo “${name}” criado` })).toBeVisible();
  const card = page.getByRole("form", { name: `Editar grupo ${name}`, exact: true });
  await expect(card.locator(".management-group-preview img")).toHaveAttribute("src", /\/media\/group-covers\/.*\.webp$/);
  const href = await card.getByRole("link", { name: "Ver página" }).getAttribute("href");
  const publicGroup = await page.request.get(`/api${href.replace("/grupos/", "/groups/")}`);
  const group = await publicGroup.json();
  expect(group.cover_alt).toBe("Foto de teste do novo grupo");
  await page.goto(href);
  await expect(page.locator(".editorial-group-detail img")).toHaveAttribute("src", group.cover_url);
  await page.goto("/index.html");
  await expect(page.locator(`.mag-group[href="${href}"] img`)).toHaveAttribute("src", group.cover_url);
  await page.goto("/painel/grupos");
  await card.getByLabel("Escolher foto do grupo").setInputFiles(process.env.CUC_GROUP_PHOTO);
  await card.getByRole("textbox", { name: "Descrição da foto", exact: true }).fill("Foto atualizada do grupo");
  await card.getByRole("button", { name: "Salvar página do grupo" }).click();
  await expect(card.getByRole("status")).toContainText("atualizada");
  const updated = await page.request.get(`/api/groups/${group.slug}`);
  const updatedGroup = await updated.json();
  expect(updatedGroup.cover_url).not.toBe(group.cover_url);
  expect(updatedGroup.cover_alt).toBe("Foto atualizada do grupo");
  await page.goto(href);
  await expect(page.locator(".editorial-group-detail img")).toHaveAttribute("src", updatedGroup.cover_url);
  expect(errors).toEqual([]);
});
